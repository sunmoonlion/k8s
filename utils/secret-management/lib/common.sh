# =============================================================================
# 配置读取函数
# =============================================================================

# 读取配置值（从环境变量中读取，因为配置文件已经source）
get_config() {
    local key="$1"
    local default="${2:-}"
    
    # 从环境变量中读取
    local value="${!key:-$default}"
    echo "$value"
}

# =============================================================================
# 日志函数
# =============================================================================

log_success() { echo "✅ $*"; }
log_info() { echo "ℹ️  $*"; }
log_warn() { echo "⚠️  $*"; }
log_error() { echo "❌ $*"; }
log_debug() { echo "🔍 $*"; }
